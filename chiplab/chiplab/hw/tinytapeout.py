TT_TOOLS = Path(getattr(config, "TT_TOOLS", None) or os.environ.get("CHIPLAB_TT_TOOLS") or (Path(config.PDK_ROOT).parent / "tt"))
TT_TEMPLATE = Path(os.environ.get("CHIPLAB_TT_TEMPLATE") or (TT_TOOLS.parent / "template"))
TT_TOOLS_URL = "https://github.com/TinyTapeout/tt-support-tools"
TT_TEMPLATE_URL = "https://github.com/TinyTapeout/ttsky-verilog-template"
LIBRELANE_TAG = "3.0.14"


def ensure_tt_assets() -> None:
    """Shallow-clone tt-support-tools and the ttsky Verilog template if they are not there yet."""
    for url, path in ((TT_TOOLS_URL, TT_TOOLS), (TT_TEMPLATE_URL, TT_TEMPLATE)):
        if not (path / ".git").exists():
            path.parent.mkdir(parents=True, exist_ok=True)
            subprocess.run(["git", "clone", "-q", "--depth", "1", url, str(path)], check=True, timeout=600)


def tt_python() -> str:
    """Interpreter with tt-support-tools' requirements (gitpython, pyyaml, chevron): CHIPLAB_TT_PYTHON, else this
    interpreter if it has them, else a venv next to tt-support-tools."""
    configured = str(getattr(config, "TT_PYTHON", "") or os.environ.get("CHIPLAB_TT_PYTHON", ""))
    if configured:
        return configured
    if all(importlib.util.find_spec(m) for m in ("git", "yaml", "chevron")):
        return sys.executable
    for cand in (TT_TOOLS.parent / "venv" / "bin" / "python", TT_TOOLS / ".venv" / "bin" / "python"):
        if cand.exists():
            return str(cand)
    return sys.executable
TILE_UM = {"1x1": (161.0, 111.52), "1x2": (161.0, 225.76), "2x2": (334.88, 225.76), "3x2": (508.76, 225.76),
           "4x2": (682.64, 225.76), "6x2": (1030.4, 225.76), "8x2": (1378.16, 225.76)}


def minimal_stream_wrapper(core_top: str, lanes: int, bits: int, out_bits: int, top: str | None = None) -> tuple[str, str]:
    """Fallback TT wrapper (emit/stream.py is the full one): one lane per rising edge of ui_in[7], value on
    ui_in[bits-1:0]; after `lanes` strobes uo_out = {valid, outputs}. Returns (verilog, top)."""
    if bits > 7 or out_bits > 7:
        raise ValueError("minimal wrapper supports lane bits <= 7 and outputs <= 7 bits")
    top = top or f"tt_um_chipin_{core_top.removeprefix('chip_')}"
    W, cw = lanes * bits, max(1, math.ceil(math.log2(lanes + 1)))
    unused_ui = f"ui_in[6:{bits}], " if bits < 7 else ""
    pad = 8 - out_bits - 1
    v = f"""`default_nettype none
// chipin.space chip lab: Tiny Tapeout streaming wrapper around {core_top}. Generated; do not edit.
module {top} (
    input  wire [7:0] ui_in,    // ui_in[{bits - 1}:0] lane value, ui_in[7] strobe (rising edge)
    output wire [7:0] uo_out,   // uo_out[{out_bits - 1}:0] decision, uo_out[{out_bits}] valid
    input  wire [7:0] uio_in,
    output wire [7:0] uio_out,
    output wire [7:0] uio_oe,
    input  wire       ena,
    input  wire       clk,
    input  wire       rst_n
);
  reg [{W - 1}:0] win;
  reg [{cw - 1}:0] count;
  reg strobe_q;
  reg [{out_bits - 1}:0] y_q;
  reg valid_q;
  wire [{out_bits - 1}:0] y_core;
  {core_top} core (.x(win), .y(y_core));
  always @(posedge clk) begin
    if (!rst_n) begin
      win <= {W}'d0; count <= {cw}'d0; strobe_q <= 1'b0; y_q <= {out_bits}'d0; valid_q <= 1'b0;
    end else begin
      strobe_q <= ui_in[7];
      if (ui_in[7] && !strobe_q) begin
        win <= {{ui_in[{bits - 1}:0], win[{W - 1}:{bits}]}};
        if (count != {cw}'d{lanes}) count <= count + {cw}'d1;
      end
      valid_q <= (count == {cw}'d{lanes});
      y_q <= y_core;
    end
  end
  assign uo_out = {{{pad}'d0, valid_q, y_q}};
  assign uio_out = 8'd0;
  assign uio_oe = 8'd0;
  wire _unused = &{{ena, {unused_ui}uio_in, 1'b0}};
endmodule
"""
    if bits == 7:
        v = v.replace("ui_in[6:7], ", "")
    return v, top


def _info_yaml(meta: dict, top: str, sources: list[str], tiles: str, clock_hz: int) -> str:
    pins = meta.get("pinout", {})
    lines = ["# Tiny Tapeout project information (generated by the chipin.space chip lab)", "project:",
             f"  title:        \"{meta.get('title', top)}\"", f"  author:       \"{meta.get('author', 'chipin.space chip lab')}\"",
             f"  discord:      \"{meta.get('discord', '')}\"", f"  description:  \"{meta.get('description', 'AI-designed sensing chip')}\"",
             "  language:     \"Verilog\"", f"  clock_hz:     {clock_hz}", f"  tiles: \"{tiles}\"", f"  top_module:  \"{top}\"",
             "  source_files:"] + [f"    - \"{s}\"" for s in sources] + ["", "pinout:"]
    for grp in ("ui", "uo", "uio"):
        for i in range(8):
            lines.append(f"  {grp}[{i}]: \"{pins.get(f'{grp}[{i}]', '')}\"")
    lines += ["", "yaml_version: 6", ""]
    return "\n".join(lines)


_TEST_PY = '''# SPDX-License-Identifier: Apache-2.0
# Generated by the chipin.space chip lab: streams each test vector into the chip and checks the decision.
import json
from pathlib import Path

import cocotb
from cocotb.clock import Clock
from cocotb.triggers import ClockCycles


@cocotb.test()
async def test_vectors(dut):
    spec = json.loads((Path(__file__).parent / "vectors.json").read_text())
    bits, outw = spec["bits"], spec["out_bits"]
    cocotb.start_soon(Clock(dut.clk, 10, unit="us").start())
    dut.ena.value = 1
    dut.ui_in.value = 0
    dut.uio_in.value = 0
    dut.rst_n.value = 0
    await ClockCycles(dut.clk, 5)
    dut.rst_n.value = 1
    await ClockCycles(dut.clk, 2)
    fails = 0
    for n, vec in enumerate(spec["vectors"]):
        for lane in vec["lanes"]:
            dut.ui_in.value = lane & ((1 << bits) - 1)
            await ClockCycles(dut.clk, 1)
            dut.ui_in.value = (1 << 7) | (lane & ((1 << bits) - 1))
            await ClockCycles(dut.clk, 1)
        dut.ui_in.value = 0
        await ClockCycles(dut.clk, 3)
        out = int(dut.uo_out.value)
        valid = (out >> outw) & 1
        got = out & ((1 << outw) - 1)
        if not valid or got != vec["expect"]:
            fails += 1
            dut._log.error(f"vector {n}: expected {vec['expect']} got {got} valid {valid}")
    dut._log.info(f"{len(spec['vectors']) - fails}/{len(spec['vectors'])} vectors matched")
    assert fails == 0
'''


def _shims() -> Path:
    """tt-support-tools calls `yowasp-yosys` (WebAssembly, sandboxed filesystem); point it at native Yosys."""
    d = config.home("shims")
    sh = d / "yowasp-yosys"
    if not sh.exists():
        sh.write_text(f"#!/bin/sh\nexec {config.oss_bin('yosys')} \"$@\"\n")
        sh.chmod(0o755)
    return d


def _env() -> dict:
    env = os.environ.copy()
    env.update({"PDK_ROOT": str(config.PDK_ROOT), "LIBRELANE_TAG": LIBRELANE_TAG})
    env["PATH"] = f"{_shims()}:{Path(tt_python()).parent}:{env['PATH']}"
    return env


def pick_tiles(rtl_files: list[Path], top_module: str, workdir: Path, pdk: str = "sky130A", density: float = 0.55) -> dict:
    """Smallest TT tile size whose area fits the design's Liberty-mapped cell area at the target density."""
    from chiplab.hw.pdk import map_to_process
    key = {"sky130A": "sky130", "gf180mcuD": "gf180", "ihp-sg13g2": "ihp"}[pdk]
    merged = Path(workdir) / "tiles_estimate.v"
    merged.parent.mkdir(parents=True, exist_ok=True)
    merged.write_text("\n".join(Path(f).read_text() for f in rtl_files))
    m = map_to_process(merged, top_module, Path(workdir) / "tiles_estimate", key)
    need = (m["area_um2"] or 0) / density
    for t, (w, h) in TILE_UM.items():
        if w * h >= need:
            return {"tiles": t, "cell_area_um2": m["area_um2"], "density": density, "tile_area_um2": round(w * h, 1)}
    return {"tiles": None, "cell_area_um2": m["area_um2"], "density": density, "error": "larger than 8x2 tiles"}


def tt_package(rtl_files: list[Path], top_module: str, workdir: Path, design_meta: dict, tiles: str = "auto",
               harden: bool = False, pdk: str = "sky130A", vectors: dict | None = None, clock_hz: int = 25_000_000,
               timeout: int = 5400) -> dict:
    """Create a TT project folder (and optionally harden it). vectors: {"bits", "out_bits", "vectors": [{lanes, expect}]}
    from the integer model; they drive the RTL test (level 3) and the gate-level test (level 4)."""
    t0 = time.time()
    ensure_tt_assets()
    tile_choice = None
    if tiles == "auto":
        tile_choice = pick_tiles(rtl_files, top_module, workdir, pdk)
        if not tile_choice["tiles"]:
            raise ValueError(f"design too large for Tiny Tapeout: {tile_choice}")
        tiles = tile_choice["tiles"]
    if tiles not in TILE_UM:
        raise ValueError(f"tiles must be 'auto' or one of {list(TILE_UM)}")
    proj = Path(workdir) / f"tt_{top_module}"
    if proj.exists():
        shutil.rmtree(proj)
    (proj / "src").mkdir(parents=True)
    (proj / "docs").mkdir()
    (proj / "test").mkdir()
    sources = []
    for f in rtl_files:
        shutil.copy(f, proj / "src" / Path(f).name)
        sources.append(Path(f).name)
    cfg_txt = (TT_TEMPLATE / "src" / "config.json").read_text()
    period_ns = round(1e9 / clock_hz, 3)  # sensor decisions are slow: default 25 MHz leaves timing margin
    cfg_txt = cfg_txt.replace('"CLOCK_PERIOD": 20,', f'"CLOCK_PERIOD": {period_ns},')
    (proj / "src" / "config.json").write_text(cfg_txt)
    for name in ("LICENSE",):
        if (TT_TEMPLATE / name).exists():
            shutil.copy(TT_TEMPLATE / name, proj / name)
    (proj / "info.yaml").write_text(_info_yaml(design_meta, top_module, sources, tiles, clock_hz))
    (proj / "docs" / "info.md").write_text(
        f"## How it works\n\n{design_meta.get('how', 'A fixed-weight integer model wired into logic gates, designed by an AI scientist in the chipin.space chip lab.')}\n\n"
        f"## How to test\n\nStream one input value per rising edge of ui_in[7] on ui_in[6:0]; after a full window the "
        f"decision appears on uo_out with a valid bit.\n\n## External hardware\n\nNone.\n")
    # test bench from the template, pointed at our top module and sources
    tb = (TT_TEMPLATE / "test" / "tb.v").read_text().replace("tt_um_example", top_module)
    (proj / "test" / "tb.v").write_text(tb)
    mk = (TT_TEMPLATE / "test" / "Makefile").read_text().replace("PROJECT_SOURCES = project.v", "PROJECT_SOURCES = " + " ".join(sources))
    (proj / "test" / "Makefile").write_text(mk)
    (proj / "test" / "test.py").write_text(_TEST_PY)
    if vectors:
        (proj / "test" / "vectors.json").write_text(json.dumps(vectors))
    # tt-support-tools expects ./tt inside the project (FP_DEF_TEMPLATE is dir::../tt/tech/...)
    shutil.copytree(TT_TOOLS, proj / "tt", ignore=shutil.ignore_patterns("__pycache__"), symlinks=True)  # keeps tt/.git (tt_tool reads its version)
    (proj / ".gitignore").write_text("runs/\ntt/\ntest/sim_build/\ntest/results.xml\n*.fst\n")
    git = lambda *a: subprocess.run(["git", *a], cwd=proj, capture_output=True, text=True)
    git("init", "-q"); git("add", "-A")
    git("-c", "user.name=chipin.space chip lab", "-c", "user.email=lab@chipin.space", "commit", "-q", "-m", "chip lab: TT project")
    env = _env()
    tt = lambda *a, t=timeout: subprocess.run([tt_python(), "tt/tt_tool.py", "--pdk", pdk, *a], cwd=proj, env=env,
                                              capture_output=True, text=True, timeout=t)
    r = tt("--create-user-config", t=600)
    out = {"folder": str(proj), "top": top_module, "tiles": tiles, "tile_um": TILE_UM[tiles], "pdk": pdk, "tile_choice": tile_choice,
           "user_config_ok": r.returncode == 0, "harden_ok": None, "gds": None, "png": None, "gl_test_passed": None}
    if r.returncode != 0:
        out["error"] = (r.stdout + r.stderr)[-1500:]
        out["seconds"] = round(time.time() - t0, 1)
        return out
    rtl_test = run_cocotb(proj, gates=False) if vectors else None
    out["rtl_test_passed"] = rtl_test["passed"] if rtl_test else None
    if harden:
        out.update(harden_project(proj, pdk, timeout, vectors is not None))
    out["seconds"] = round(time.time() - t0, 1)
    return out


def harden_project(proj: Path, pdk: str = "sky130A", timeout: int = 5400, gl_test: bool = True) -> dict:
    """The same LibreLane run tt_tool.py --harden performs (src/config_merged.json, run tag wokwi), executed in the
    LibreLane image, so the host needs Docker but no LibreLane install."""
    from chiplab.hw.librelane import LayoutError, run_librelane
    env = _env()
    tt = lambda *a, t=timeout: subprocess.run([tt_python(), "tt/tt_tool.py", "--pdk", pdk, *a], cwd=proj, env=env,
                                              capture_output=True, text=True, timeout=t)
    t0 = time.time()
    shutil.rmtree(proj / "runs" / "wokwi", ignore_errors=True)
    (proj / "runs" / "wokwi").mkdir(parents=True, exist_ok=True)
    try:
        r = run_librelane(proj, "src/config_merged.json", pdk, "wokwi", timeout, force_run_dir="runs/wokwi")
    except LayoutError as e:
        return {"harden_ok": False, "error": str(e), "harden_seconds": round(time.time() - t0, 1)}
    (proj / "harden.log").write_text(r.stdout[-200000:] + r.stderr[-50000:])
    final = proj / "runs" / "wokwi" / "final"
    res = {"harden_ok": r.returncode == 0 and final.exists(), "harden_seconds": round(time.time() - t0, 1)}
    if not res["harden_ok"]:
        res["error"] = (r.stdout + r.stderr)[-2000:]
        return res
    gds = sorted((final / "gds").glob("*.gds"))
    res["gds"] = str(gds[0]) if gds else None
    try:
        st = tt("--print-stats", t=600)
        res["stats"] = st.stdout[-2000:]
    except Exception as e:  # optional
        res["stats"] = f"not available: {e}"
    m = final / "metrics.csv"
    if m.exists():
        rows = {row[0]: row[1] for row in csv.reader(m.open()) if len(row) >= 2}
        keep = ("design__instance__count", "design__instance__area", "design__instance__utilization", "timing__setup__ws",
                "timing__hold__ws", "power__total", "route__wirelength", "design__die__area")
        res["metrics"] = {k: rows[k] for k in keep if k in rows}
        res["utilisation"] = rows.get("design__instance__utilization")
    mj = final / "metrics.json"
    if mj.exists() and "metrics" not in res:
        d = json.loads(mj.read_text())
        res["metrics"] = {k: d[k] for k in d if k.startswith(("design__instance", "timing__setup__ws", "power__total"))}
        res["utilisation"] = d.get("design__instance__utilization")
    if shutil.which("rsvg-convert") and shutil.which("pngquant"):
        p = tt("--create-png", t=900)
        pngs = sorted(proj.glob("*.png")) + sorted((proj / "runs").rglob("*.png"))
        res["png"] = str(pngs[0]) if p.returncode == 0 and pngs else None
    else:
        from chiplab.hw.librelane import render_png  # KLayout inside the LibreLane image
        res["png"] = render_png(Path(res["gds"]), proj / f"{proj.name}.png") if res.get("gds") else None
        res["png_note"] = "rendered with KLayout in the LibreLane image (rsvg-convert/pngquant not installed)"
    if gl_test:
        pnl = sorted((final / "pnl").glob("*.pnl.v")) or sorted((final / "nl").glob("*.nl.v"))
        if pnl:
            shutil.copy(pnl[0], proj / "test" / "gate_level_netlist.v")
            g = run_cocotb(proj, gates=True)
            res["gl_test_passed"] = g["passed"]
            res["gl_test_log"] = g["log"]
    return res


def run_cocotb(proj: Path, gates: bool) -> dict:
    """Run the project's cocotb test (RTL or gate-level) with Icarus from the OSS CAD Suite."""
    env = os.environ.copy()
    # OSS CAD Suite's vvp pins PYTHONHOME to its own Python, so use its bundled cocotb too
    env["PATH"] = f"{Path(config.oss_bin('iverilog')).parent}:{env['PATH']}"
    for k in ("VIRTUAL_ENV", "PYTHONPATH", "PYTHONHOME"):
        env.pop(k, None)
    env["PDK_ROOT"] = str(config.PDK_ROOT)
    env["PWD"] = str(proj / "test")  # the template Makefile resolves sources from $(PWD)
    args = ["make", "-B"] + (["GATES=yes"] if gates else [])
    t0 = time.time()
    p = subprocess.run(args, cwd=proj / "test", env=env, capture_output=True, text=True, timeout=1800)
    log = proj / "test" / ("gl_test.log" if gates else "rtl_test.log")
    log.write_text(p.stdout + p.stderr)
    res_xml = proj / "test" / "results.xml"
    passed = p.returncode == 0 and res_xml.exists() and "failure" not in res_xml.read_text()
    return {"passed": passed, "log": str(log), "seconds": round(time.time() - t0, 1)}
