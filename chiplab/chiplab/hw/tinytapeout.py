"""Tiny Tapeout packaging: a ready-to-submit TT project folder (ttsky-verilog-template layout), optional local
harden with tt-support-tools (LibreLane in Docker), PNG render and the gate-level test (verification level 4).

Wraps, never reimplements: tt-support-tools (Apache-2.0) and the ttsky-verilog-template layout (Apache-2.0).
"""
