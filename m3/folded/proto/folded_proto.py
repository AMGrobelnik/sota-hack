"""Prototype of a folded (time-shared) neuron: weights in a constant case-statement ROM, P multiply-accumulate
units, an activation register file and a small controller. Checked bit for bit against the chip lab's integer
model (chiplab.ir.interp) with Icarus, and mapped to sky130 / gf180 next to the lab's fully wired chip of the same
neuron.

  python folded_proto.py sim  --n 256 --p 1 --wtype ternary --vectors 200
  python folded_proto.py area --n 256 --p 4 --wtype uniform4
"""
from __future__ import annotations

import argparse
import json
import math
import random
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ABITS = 4        # unsigned activations 0..15
ACCW = 24        # accumulator width (ample for N <= 4096 at 4-bit weights)
PARAMS = {"ternary": {"wb": 2, "amax": 15}, "uniform4": {"wb": 4, "amax": 15}}


def make_model(n: int, wtype: str, seed: int) -> dict:
    """Random neuron. Bias and shift are set from the weights so that, for uniform random activations, the
    pre-clip output is centred near 6 with a spread of about 5 (outputs cover 0..amax, not one clipped value)."""
    rng = random.Random(seed)
    if wtype == "ternary":
        w = [rng.choices([0, 1, -1], weights=[0.5, 0.25, 0.25])[0] for _ in range(n)]
    else:
        w = [rng.randrange(-8, 8) for _ in range(n)]
    std = math.sqrt(sum(v * v for v in w) * 21.25)          # Var of uniform 0..15 is 21.25
    shift = max(0, round(math.log2(max(std, 1) / 5)))
    p = {**PARAMS[wtype], "shift": shift, "bias": -round(7.5 * sum(w)) + 6 * 2 ** shift}
    ir = {"ir": "chipir/1", "name": f"folded_neuron_{wtype}_{n}",
          "inputs": [{"name": "x", "lanes": n, "bits": ABITS, "signed": False}],
          "nodes": [{"id": "h", "op": "matvec", "src": "x", "W": [w], "b": [p["bias"]]},
                    {"id": "s", "op": "shift", "src": "h", "k": p["shift"]},
                    {"id": "y", "op": "clip", "src": "s", "lo": 0, "hi": p["amax"]}],
          "outputs": [{"name": "y", "src": "y"}], "meta": {"family": "folded-proto", "wtype": wtype, "seed": seed}}
    return {"w": w, "ir": ir, **p}


def wcode(w: int, wb: int) -> int:
    if wb == 2:
        return {0: 0b00, 1: 0b01, -1: 0b11}[w]
    return w & 0xF


def folded_verilog(m: dict, n: int, pm: int) -> str:
    """Folded neuron: one ROM word (pm weights) per cycle, pm MACs, n/pm cycles per output."""
    wb, steps = m["wb"], n // pm
    assert n % pm == 0 and pm & (pm - 1) == 0, "n must be a multiple of p, p a power of two"
    aw, sw = max(1, (n - 1).bit_length()), max(1, (steps - 1).bit_length())
    pw = max(0, (pm - 1).bit_length())
    ob = max(1, m["amax"].bit_length())
    word = wb * pm
    rom = []
    for s in range(steps):
        v = 0
        for j in range(pm):
            v |= wcode(m["w"][s * pm + j], wb) << (j * wb)
        rom.append(f"      {sw}'d{s}: wword = {word}'h{v:0{(word + 3) // 4}x};")
    terms = []
    for j in range(pm):
        idx = "step" if pm == 1 else f"{{step, {pw}'d{j}}}"
        terms.append(f"  wire [{wb - 1}:0] w{j} = wword[{j * wb + wb - 1}:{j * wb}];")
        terms.append(f"  wire signed [{ACCW - 1}:0] a{j} = {{{{{ACCW - ABITS}{{1'b0}}}}, act[{idx}]}};")
        if wb == 2:
            terms.append(f"  wire signed [{ACCW - 1}:0] t{j} = (w{j} == 2'b01) ? a{j} : (w{j} == 2'b11) ? -a{j} : "
                         f"{ACCW}'sd0;")
        else:
            terms.append(f"  wire signed [{ACCW - 1}:0] t{j} = $signed({{{{{ACCW - wb}{{w{j}[{wb - 1}]}}}}, w{j}}}) * a{j};")
    total = " + ".join(f"t{j}" for j in range(pm))
    return f"""// Folded neuron, generated by folded_proto.py: {n} weights in ROM, {pm} MAC(s),
// {steps} cycles per output. y = clip((sum_i w_i * x_i + {m['bias']}) >>> {m['shift']}, 0, {m['amax']}).
module folded_neuron(input wire clk, input wire rst,
    input wire ld, input wire [{aw - 1}:0] ld_addr, input wire [{ABITS - 1}:0] ld_data,
    input wire start, output reg done, output wire [{ob - 1}:0] y);
  reg [{ABITS - 1}:0] act [0:{n - 1}];
  always @(posedge clk) if (ld) act[ld_addr] <= ld_data;
  reg [{sw - 1}:0] step;
  reg busy;
  reg signed [{ACCW - 1}:0] acc;
  reg [{word - 1}:0] wword;
  always @(*) begin
    case (step)
{chr(10).join(rom)}
      default: wword = {word}'h0;
    endcase
  end
{chr(10).join(terms)}
  always @(posedge clk) begin
    if (rst) begin
      busy <= 1'b0; done <= 1'b0; step <= {sw}'d0; acc <= {ACCW}'sd0;
    end else if (start && !busy) begin
      busy <= 1'b1; done <= 1'b0; step <= {sw}'d0; acc <= {ACCW}'sd{m['bias']};
    end else if (busy) begin
      acc <= acc + {total};
      step <= step + 1'b1;
      if (step == {sw}'d{steps - 1}) begin busy <= 1'b0; done <= 1'b1; end
    end
  end
  wire signed [{ACCW - 1}:0] sh = acc >>> {m['shift']};
  assign y = (sh < 0) ? {ob}'d0 : (sh > {m['amax']}) ? {ob}'d{m['amax']} : sh[{ob - 1}:0];
endmodule
"""


def testbench(n: int, nvec: int, steps: int, ob: int) -> str:
    aw = max(1, (n - 1).bit_length())
    return f"""`timescale 1ns/1ps
module tb;
  reg clk = 0, rst = 1, ld = 0, start = 0;
  reg [{aw - 1}:0] ld_addr = 0;
  reg [{ABITS - 1}:0] ld_data = 0;
  wire done;
  wire [{ob - 1}:0] y;
  reg [{ABITS - 1}:0] xs [0:{n * nvec - 1}];
  reg [7:0] ys [0:{nvec - 1}];
  integer v, i, bad = 0, cyc, maxcyc = 0;
  folded_neuron dut(.clk(clk), .rst(rst), .ld(ld), .ld_addr(ld_addr), .ld_data(ld_data), .start(start), .done(done), .y(y));
  always #5 clk = ~clk;
  initial begin
    $readmemh("x.hex", xs);
    $readmemh("y.hex", ys);
    @(posedge clk); #1 rst = 0;
    for (v = 0; v < {nvec}; v = v + 1) begin
      for (i = 0; i < {n}; i = i + 1) begin
        ld = 1; ld_addr = i; ld_data = xs[v * {n} + i]; @(posedge clk); #1;
      end
      ld = 0; start = 1; @(posedge clk); #1 start = 0; cyc = 0;
      while (!done) begin @(posedge clk); #1 cyc = cyc + 1; end
      if (cyc > maxcyc) maxcyc = cyc;
      if (y !== ys[v][{ob - 1}:0]) begin
        bad = bad + 1;
        if (bad < 5) $display("vector %0d: got %0d want %0d", v, y, ys[v]);
      end
    end
    $display("VECTORS %0d MISMATCH %0d CYCLES %0d", {nvec}, bad, maxcyc);
    $finish;
  end
endmodule
"""


def vectors(n: int, nvec: int, seed: int) -> list[list[int]]:
    """Edge cases first (all zero, all max, alternating), then uniform random activations."""
    rng = random.Random(seed + 1000)
    vs = [[0] * n, [15] * n, [15 if i % 2 else 0 for i in range(n)], [0 if i % 2 else 15 for i in range(n)]]
    while len(vs) < nvec:
        vs.append([rng.randrange(16) for _ in range(n)])
    return vs[:nvec]


def sim(n: int, pm: int, wtype: str, nvec: int, seed: int, wd: Path) -> dict:
    import numpy as np

    from chiplab.config import oss_bin
    from chiplab.ir import interp
    from chiplab.ir.schema import validate
    m = make_model(n, wtype, seed)
    validate(m["ir"])
    wd.mkdir(parents=True, exist_ok=True)
    xs = vectors(n, nvec, seed)
    want = interp.run(m["ir"], {"x": np.asarray(xs)})["y"][:, 0].tolist()
    ob = max(1, m["amax"].bit_length())
    (wd / "folded_neuron.v").write_text(folded_verilog(m, n, pm))
    (wd / "tb.v").write_text(testbench(n, nvec, n // pm, ob))
    (wd / "x.hex").write_text("\n".join(f"{a:x}" for v in xs for a in v) + "\n")
    (wd / "y.hex").write_text("\n".join(f"{y:02x}" for y in want) + "\n")
    (wd / "ir.json").write_text(json.dumps(m["ir"]))
    subprocess.run([oss_bin("iverilog"), "-g2012", "-o", "tb.vvp", "tb.v", "folded_neuron.v"], cwd=wd, check=True,
                   capture_output=True, text=True, timeout=600)
    out = subprocess.run([oss_bin("vvp"), "-n", "tb.vvp"], cwd=wd, check=True, capture_output=True, text=True,
                         timeout=1800).stdout
    r = re.search(r"VECTORS (\d+) MISMATCH (\d+) CYCLES (\d+)", out)
    hist = {k: want.count(k) for k in sorted(set(want))}
    return {"n": n, "p": pm, "wtype": wtype, "seed": seed, "vectors": int(r.group(1)), "mismatches": int(r.group(2)),
            "cycles_per_output": int(r.group(3)), "ok": int(r.group(2)) == 0, "output_histogram": hist,
            "log": r.group(0)}


def area(n: int, pm: int, wtype: str, seed: int, wd: Path, timeout: int) -> dict:
    """Map the folded neuron and the lab's fully wired chip of the same neuron onto sky130 and gf180."""
    from chiplab import tools_hw  # noqa: F401  registers map_to_process
    from chiplab.hw.pdk import map_to_process
    from chiplab.hw.yosys import synth_generic
    from chiplab.tools import TOOLS
    m = make_model(n, wtype, seed)
    wd.mkdir(parents=True, exist_ok=True)
    rtl = wd / "folded_neuron.v"
    rtl.write_text(folded_verilog(m, n, pm))
    res = {"n": n, "p": pm, "wtype": wtype, "seed": seed, "bias": m["bias"], "shift": m["shift"],
           "folded": {}, "wired": {}}
    g = synth_generic(rtl, "folded_neuron", wd / "folded_generic", timeout=timeout)
    res["folded"]["generic"] = {"gates": g["gates"], "depth": g["depth"]}
    for pdk in ("sky130", "gf180"):
        r = map_to_process(rtl, "folded_neuron", wd / f"folded_{pdk}", pdk, timeout=timeout)
        res["folded"][pdk] = {k: r[k] for k in ("area_um2", "gate_equivalents", "std_cells", "cells_by_type")}
    c = TOOLS["compile_verilog"]["fn"](ir=m["ir"])
    res["wired"]["design_id"] = c["design_id"]
    s = TOOLS["synthesize"]["fn"](design_id=c["design_id"])
    res["wired"]["generic"] = s.get("metrics") or {"error": s.get("error", "")[-300:]}
    for pdk in ("sky130", "gf180"):
        r = TOOLS["map_to_process"]["fn"](design_id=c["design_id"], pdk=pdk)
        res["wired"][pdk] = r.get("metrics") or {"error": r.get("error", "")[-300:]}
    add_wired_cells(res)
    return res


def add_wired_cells(res: dict) -> None:
    """Copy the cell counts of the lab's mapped wired chip (design folder pdk_<pdk>.json) into the result."""
    from chiplab import config
    d = config.HOME / "designs" / res["wired"]["design_id"]
    for pdk in ("sky130", "gf180"):
        f = d / f"pdk_{pdk}.json"
        if f.exists() and "area_um2" in res["wired"].get(pdk, {}):
            res["wired"][pdk]["cells_by_type"] = json.loads(f.read_text())["cells_by_type"]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["sim", "area"])
    ap.add_argument("--n", type=int, default=256)
    ap.add_argument("--p", type=int, default=1)
    ap.add_argument("--wtype", choices=list(PARAMS), default="ternary")
    ap.add_argument("--vectors", type=int, default=200)
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--work", default=str(HERE.parent / "work" / "proto"))
    ap.add_argument("--timeout", type=int, default=900)
    ap.add_argument("--out", default="")
    a = ap.parse_args()
    wd = Path(a.work) / f"{a.cmd}_{a.wtype}_n{a.n}_p{a.p}"
    if a.cmd == "sim":
        r = sim(a.n, a.p, a.wtype, a.vectors, a.seed, wd)
    else:
        r = area(a.n, a.p, a.wtype, a.seed, wd, a.timeout)
    if a.out:
        Path(a.out).write_text(json.dumps(r, indent=1))
    print(json.dumps({k: v for k, v in r.items()}, default=str)[:3000])
    if a.cmd == "sim" and not r["ok"]:
        sys.exit(1)


if __name__ == "__main__":
    main()
