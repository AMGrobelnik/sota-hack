#!/usr/bin/env python3
"""Generate the site front page index.html from the newest landing page, variants/z3.html.

The copy is z3 with every "../" path made root-relative: "../assets/x" becomes "./assets/x"
(not bare "assets/x", which the import map would reject as a module specifier).
Nothing else changes, so re-run this after editing variants/z3.html:

    python3 tools/make_front.py

The old variant gallery that used to be the front page is archived at r4/.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

SITE = Path(__file__).resolve().parent.parent
SRC = SITE / "variants" / "z3.html"
DEST = SITE / "index.html"
# "../" right after a quote or an opening parenthesis: src, href, import map entries, url(...).
UP = re.compile(r"""(["'(])\.\./""")
LEFTOVER = re.compile(r"""["'(]\.\./|waitlist""", re.IGNORECASE)
HEADER = "<!-- Generated by tools/make_front.py from variants/z3.html. Edit that file and re-run. -->\n"


class FrontError(RuntimeError):
    """variants/z3.html could not be turned into a clean front page."""


def convert(html: str) -> str:
    """Return the front-page copy of z3, or raise FrontError."""
    out = UP.sub(r"\1./", html)
    left = sorted({m.group(0) for m in LEFTOVER.finditer(out)})
    if left:
        raise FrontError(f"left behind after rewrite: {', '.join(left)}")
    doctype_end = out.find(">") + 1 if out.lower().startswith("<!doctype") else 0
    return out[:doctype_end] + "\n" + HEADER + out[doctype_end:].lstrip("\n")


def main() -> int:
    try:
        DEST.write_text(convert(SRC.read_text(encoding="utf-8")), encoding="utf-8")
    except (OSError, FrontError) as err:
        print(f"make_front: FAILED: {err}", file=sys.stderr)
        return 1
    print(f"wrote {DEST.relative_to(SITE)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
