#!/usr/bin/env python3
"""Generate the join-waitlist copies waitlist/y1-y5.html, x1-x5.html, v1-v5.html and w1-w10.html from variants/,
and waitlist/index.html (the page at /waitlist/) from variants/z3.html.

Each copy is the landing variant with every "Try now" call to action relabelled
"Join waitlist" and every link to ../dashboard/ pointed at join.html?v=N (N is 1-5 for v, "wN" for w).
The z3 landing carries no waitlist at all, so its copy first gets the waitlist parts below put back
(the count under the hero, the "Who is waiting" section with its world map, its chapter-rail dot and the
waitlist scripts). Nothing else changes, so re-run this after editing a variant:

    python3 tools/make_waitlist.py
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

SITE = Path(__file__).resolve().parent.parent
SRC_DIR = SITE / "variants"
OUT_DIR = SITE / "waitlist"
MAIN = "z3"  # the variant shown at /waitlist/ (also set as the join page's back target)
VARIANTS = [f"y{i}" for i in range(1, 6)] + [f"x{i}" for i in range(1, 6)] + [f"v{i}" for i in range(1, 6)] + [f"w{i}" for i in range(1, 11)]

TRY_LABEL = re.compile(r">(\s*)Try now(\s*)<")
DASH_HREF = re.compile(r"""href=(["'])\.\./dashboard/[^"']*\1""")
# Visible copy that describes the dashboard next to a Try-now button.
COPY_SWAPS = {
    "Opens the dashboard, where a run starts from your prompt.": (
        "Opens a short form to join the waitlist."
    ),
    "<!-- COPY: navigation (How it works, Try now) -->": "<!-- COPY: navigation (How it works, Join waitlist) -->",
}
LEFTOVER = re.compile(r"Try now|\.\./dashboard", re.IGNORECASE)
HEADER = "<!-- Generated by tools/make_waitlist.py from variants/{n}.html. Edit that file and re-run. -->\n"

# The waitlist parts of the z3 landing, put back only in its /waitlist/ copy: (name, anchor regex, insert).
# Each insert goes right before the anchor, or replaces group 1 when the regex has one.
WL_CSS = """/* the waitlist */
.wait { background: linear-gradient(180deg, var(--night) 0%, #101d30 100%); padding: clamp(48px, 8vh, 96px) clamp(20px, 5.4vw, 84px) clamp(64px, 10vh, 110px); --wl-accent: #5be49b; color: #e8eef5; }
.wait .wrap { display: grid; grid-template-columns: minmax(0, .72fr) minmax(0, 1.5fr); gap: clamp(24px, 4vw, 56px); align-items: center; border-top: 1px solid var(--rule); padding-top: clamp(40px, 7vh, 72px); }
.wait h2 { font-size: clamp(34px, 3.8vw, 56px); color: #fff; }
.wait .hint { margin: 14px 0 0; font-size: 16.5px; color: #c4d1df; max-width: 28ch; }
.wait .wl { font-size: 16px; margin-top: 18px; }
.pun { margin: 30px 0 14px; font-size: clamp(24px, 2.2vw, 32px); font-weight: 650; letter-spacing: -.025em; color: #fff; }
.wlmap { width: 100%; font-size: 14px; color: #b9c7d6; }
@media (max-width: 980px) { .wait .wrap { grid-template-columns: 1fr; } }

"""
WL_SECTION = """<!-- COPY: waitlist -->
<section class="wait" id="waitlist" aria-labelledby="wl-h">
  <div class="wrap">
    <div>
      <h2 id="wl-h">Who is waiting</h2>
      <p class="hint">People building medical devices, from around the world.</p>
      <p class="wl" data-waitlist-wrap hidden><span data-waitlist-count></span></p>
      <p class="pun">Come chip in.</p>
      <a class="btn" href="../dashboard/">Try now</a>
    </div>
    <div class="wlmap" data-waitlist-map></div>
  </div>
</section>

"""
WL_SCRIPTS = """<script src="../assets/waitlist-config.js"></script>
<script src="../assets/waitlist.js"></script>
<script src="../assets/waitlist-world.js"></script>
<script src="../assets/waitlist-map.js"></script>
"""
Z3_PARTS = [
    ("waitlist styles", r"/\* About and end \*/", WL_CSS),
    ("hero count", r'<div class="hero" id="hero">.*?(?=\n    </div>)', None),
    ("waitlist section", r"<!-- COPY: About -->", WL_SECTION),
    ("rail dot", r'  <li data-go="about">', '  <li data-go="waitlist"><button type="button"><span>Waitlist</span></button></li>\n'),
    ("rail target", r"var goIds = \[[^\]]*'how', ()", "'waitlist', "),
    ("waitlist scripts", r"</body>", WL_SCRIPTS),
]
HERO_COUNT = '\n      <p class="wl" data-waitlist-wrap hidden><span data-waitlist-count></span></p>'


def add_waitlist(html: str, *, name: str) -> str:
    """Put the waitlist parts back into the z3 landing, or raise WaitlistError if an anchor moved."""
    for part, anchor, insert in Z3_PARTS:
        hits = list(re.finditer(anchor, html, re.DOTALL))
        if len(hits) != 1:
            raise WaitlistError(f"{name}: anchor for the {part} found {len(hits)} times, expected once")
        m = hits[0]
        if insert is None:  # hero count: after the hero's last line
            html = html[: m.end()] + HERO_COUNT + html[m.end():]
        elif m.lastindex:
            html = html[: m.start(1)] + insert + html[m.end(1):]
        else:
            html = html[: m.start()] + insert + html[m.start():]
    return html


class WaitlistError(RuntimeError):
    """A variant could not be turned into a clean waitlist copy."""


def convert(html: str, *, n: str, name: str) -> str:
    """Return the waitlist copy of one variant, or raise WaitlistError."""
    out, labels = TRY_LABEL.subn(r">\1Join waitlist\2<", html)
    if labels == 0:
        raise WaitlistError(f"{name}: no 'Try now' call to action found")
    out = DASH_HREF.sub(lambda m: f"href={m.group(1)}join.html?v={n.removeprefix('v')}{m.group(1)}", out)
    for old, new in COPY_SWAPS.items():
        out = out.replace(old, new)
    left = sorted({m.group(0) for m in LEFTOVER.finditer(out)})
    if left:
        raise WaitlistError(f"{name}: left behind after rewrite: {', '.join(left)}")
    doctype_end = out.find(">") + 1 if out.lower().startswith("<!doctype") else 0
    return out[:doctype_end] + "\n" + HEADER.format(n=n) + out[doctype_end:].lstrip("\n")


def main() -> int:
    OUT_DIR.mkdir(exist_ok=True)
    for n in VARIANTS:
        src = SRC_DIR / f"{n}.html"
        try:
            html = src.read_text(encoding="utf-8")
            copy = convert(html, n=n, name=str(src.relative_to(SITE)))
        except (OSError, WaitlistError) as err:
            print(f"make_waitlist: FAILED: {err}", file=sys.stderr)
            return 1
        dest = OUT_DIR / f"{n}.html"
        dest.write_text(copy, encoding="utf-8")
        print(f"wrote {dest.relative_to(SITE)}")
    src = SRC_DIR / f"{MAIN}.html"
    try:
        name = str(src.relative_to(SITE))
        copy = convert(add_waitlist(src.read_text(encoding="utf-8"), name=name), n=MAIN, name=name)
    except (OSError, WaitlistError) as err:
        print(f"make_waitlist: FAILED: {err}", file=sys.stderr)
        return 1
    (OUT_DIR / "index.html").write_text(copy, encoding="utf-8")
    print("wrote waitlist/index.html")
    join = OUT_DIR / "join.html"
    text = join.read_text(encoding="utf-8")
    text, hits = re.subn(r'var MAIN = "[^"]*";', f'var MAIN = "{MAIN}";', text)
    if hits != 1:
        print("make_waitlist: FAILED: join.html has no MAIN line", file=sys.stderr)
        return 1
    join.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
